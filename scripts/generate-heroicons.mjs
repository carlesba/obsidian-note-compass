import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const sourceDir = "node_modules/heroicons/20/solid";
const target = "src/tasks/heroicons.ts";
const license = readFileSync("node_modules/heroicons/LICENSE", "utf8").trim();
const version = JSON.parse(readFileSync("node_modules/heroicons/package.json", "utf8")).version;

const icons = readdirSync(sourceDir)
	.filter((file) => file.endsWith(".svg"))
	.sort()
	.map((file) => {
		const svg = readFileSync(join(sourceDir, file), "utf8");
		const paths = [...svg.matchAll(/<path ([^>]*?)\/>/g)].map(([, attributes]) => {
			const d = /\bd="([^"]+)"/.exec(attributes)?.[1];
			const evenOdd = /fill-rule="evenodd"/.test(attributes);
			if (!d) throw new Error(`No path data in ${file}`);
			return evenOdd ? [d, 1] : [d];
		});
		return [file.replace(/\.svg$/, ""), paths];
	});

const body = icons.map(([name, paths]) => `\t${JSON.stringify(name)}: ${JSON.stringify(paths)},`).join("\n");
const header = `/*!\nHeroicons ${version}, 20px solid set, from https://heroicons.com.\nGenerated by scripts/generate-heroicons.mjs.\n\n${license}\n*/\n\n`;
writeFileSync(
	target,
	`${header}export type HeroiconPath = readonly [d: string, evenOdd?: 1];\n\nexport const HEROICONS: Readonly<Record<string, readonly HeroiconPath[]>> = {\n${body}\n};\n`,
);
console.log(`${icons.length} icons written to ${target}`);
